#ifndef __AD9910_H
#define __AD9910_H

#include "main.h" // CubeMX项目的主头文件，包含了所有引脚定义

// C类型定义
typedef unsigned char u8;
typedef unsigned short u16;
typedef unsigned long u32;

/*-----------------------------------------------------------------------------------*/
/*                              宏定义                                               */
/*-----------------------------------------------------------------------------------*/

// 定义AD9910内部RAM的长度
#define WAVE_RAM_LEN 1024

/*-----------------------------------------------------------------------------------*/
/*             引脚定义已与 main.h (CubeMX生成) 同步，无需再次修改                     */
/*-----------------------------------------------------------------------------------*/
// CubeMX已定义: AD9910_PROFILE2_Pin, AD9910_PROFILE2_GPIO_Port, 等等...


/*-----------------------------------------------------------------------------------*/
/*                              外部变量声明                                           */
/*-----------------------------------------------------------------------------------*/

// 声明一个用于存放波形数据的数组
extern u16 Waveform_RAM[WAVE_RAM_LEN];


/*-----------------------------------------------------------------------------------*/
/*                                 函数声明                                          */
/*-----------------------------------------------------------------------------------*/

/**
 * @brief  初始化AD9910芯片
 * @note   此函数假设CubeMX生成的 MX_GPIO_Init() 已被调用
 */
void Init_ad9910(void);

/**
 * @brief  (模式1: DDS) 设置频率和幅度
 * @param  Freq: 目标频率, 单位 Hz
 * @param  Amp:  目标幅度, 范围 0 - 16383 (0x3FFF)
 */
void Freq_Amp_convert(u32 Freq, u16 Amp);

/**
 * @brief  (模式2: AWG) 在STM32中生成一个示例波形(三角波)
 */
void Generate_Triangle_Wave(void);

/**
 * @brief  (模式2: AWG) 将STM32中的数组写入到AD9910的RAM中
 * @param  pData: 指向波形数据数组的指针
 * @param  len:   数据长度 (应小于或等于 WAVE_RAM_LEN)
 */
void AD9910_Write_RAM(u16* pData, u16 len);


#endif