C = textscan(str_data, '%*s %*s %f %*s %*s %*s %*s %*s %*s %f %*s', ...
    'HeaderLines', 4, 'Delimiter', {':', '(', ')', ' '}, 'MultipleDelimsAsOne', 1);

% 提取频率和增益
measured_freq = C{1};
measured_gain = C{2};

% --- 2. 绘制测量数据的频谱 ---
figure;
h1 = loglog(measured_freq, measured_gain, 'bo', 'MarkerFaceColor', 'b', 'DisplayName', 'Measured Data');
hold on;
grid on;

% --- 3. 定义并绘制拟合的传递函数 ---
% 从文本中提取拟合参数
k = 0.7429;
f0 = 18226.90;
Q = 0.1683;

% 创建一个二阶带通传递函数
% H(s) = (k * (w0/Q) * s) / (s^2 + (w0/Q)*s + w0^2)
% 其中 w0 = 2*pi*f0
w0 = 2 * pi * f0;
num = [k * (w0/Q) 0];
den = [1 (w0/Q) w0^2];
sys = tf(num, den);

% 生成频率响应
% 创建一个对数间隔的频率向量以获得平滑的曲线
freq_vector = logspace(log10(min(measured_freq)), log10(max(measured_freq)), 500);
[mag, ~, w] = bode(sys, freq_vector * 2 * pi);

