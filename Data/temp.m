% bode返回的是绝对幅值，这里直接使用即可
h2 = loglog(w/(2*pi), squeeze(mag), 'r-', 'LineWidth', 2, 'DisplayName', 'Fitted Transfer Function');

% --- 4. 格式化图表 ---
title('System Identification Verification');
xlabel('Frequency (Hz)');
ylabel('Gain');
