/**
 * @brief 测量采样板增益衰减幅度——峰峰值函数 (优化版)
 */
void SweepSampleBoardVppToA(){
    float32_t target_freq, target_vin;
    // float32_t measured_vout; // 不再需要单个的测量变量

    // 用于存储单次设置下的多次测量结果
    float32_t VoutMeasurements[MAX_ITERATIONS]; 
    float32_t mean_vout; // 用于存储计算出的平均值

    for (uint32_t i = 0; i < FREQ_NUMES_ASB; i++)
    {
        target_freq = FREQ_START + i * FREQ_STEP;
        for (uint32_t j = 0; j < VOUT_NUMES_ASB; j++)
        {
            target_vin = VOUT_START + j * VOUT_STEP;

            // 1. 设置DAC输出电压，这个动作只需要执行一次
            SetDacOutputVpp(target_vin, target_freq * 0.001f);

            // 2. 等待电路稳定，这个延时也只需要一次
            HAL_Delay(STABILIZE_DELAY_MS);

            // 3. 进行多次测量，并将结果存入数组
            for (uint32_t k = 0; k < MAX_ITERATIONS; k++)
            {
                VoutMeasurements[k] = MeasureAdcInputVpp();
                // 可以在这里加入一个极短的延时，如果ADC采样过快的话
                // HAL_Delay(1); 
            }

            // 4. 使用 ARM Math 库高效计算测量结果的平均值
            arm_mean_f32(VoutMeasurements, MAX_ITERATIONS, &mean_vout);

            // 5. 使用稳定后的平均值进行计算和存储
            AmpSampleBoard[i][j] = mean_vout / target_vin; // 计算增益衰减幅度
            VoutSampleBoard[i][j] = mean_vout;             // 记录对应的输出电压
        }
    }
}



